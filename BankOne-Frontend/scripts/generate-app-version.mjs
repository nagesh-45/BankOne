#!/usr/bin/env node
/**
 * Writes src/environments/version.generated.ts from git / CI.
 * Format: <branch>-<digits>  e.g. main-142
 * Commit part is digits-only (git commit count), not the hex SHA.
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.join(__dirname, '..');
const outFile = path.join(frontendRoot, 'src', 'environments', 'version.generated.ts');
const gitRoots = [frontendRoot, path.join(frontendRoot, '..'), process.cwd()];

function git(cmd, cwd) {
  try {
    return execSync(cmd, {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore']
    }).trim();
  } catch {
    return null;
  }
}

function firstGit(cmd) {
  for (const root of gitRoots) {
    const value = git(cmd, root);
    if (value) {
      return value;
    }
  }
  return null;
}

function resolveBranch() {
  const fromEnv = (
    process.env.BRANCH ||
    process.env.HEAD_REF ||
    process.env.GITHUB_REF_NAME ||
    process.env.RENDER_GIT_BRANCH ||
    process.env.CF_PAGES_BRANCH ||
    ''
  ).trim();
  if (fromEnv && fromEnv !== 'HEAD') {
    return fromEnv;
  }

  const ref = firstGit('git rev-parse --abbrev-ref HEAD');
  if (ref && ref !== 'HEAD') {
    return ref;
  }

  // Detached HEAD: try remote-tracking branch for this commit
  const describe = firstGit('git name-rev --name-only --exclude=tags/* HEAD');
  if (describe && describe !== 'undefined') {
    return describe.replace(/~\d+$/, '').replace(/^remotes\/origin\//, '');
  }

  return 'unknown';
}

function digitsOnly(value) {
  const digits = String(value || '').replace(/\D/g, '');
  return digits || null;
}

function resolveCommit() {
  if (process.env.APP_VERSION && process.env.APP_VERSION.trim()) {
    // Allow full override as the whole label if set
    return null;
  }

  // Prefer commit ordinal (0-9 only). Works when full history is available.
  const count = firstGit('git rev-list --count HEAD');
  if (count && /^\d+$/.test(count)) {
    return count;
  }

  // Shallow CI clone fallback: turn short hex SHA into a decimal number.
  const short =
    firstGit('git rev-parse --short=7 HEAD') ||
    (process.env.COMMIT_REF ||
      process.env.GITHUB_SHA ||
      process.env.RENDER_GIT_COMMIT ||
      process.env.CF_PAGES_COMMIT_SHA ||
      ''
    ).trim().slice(0, 7);

  if (short && /^[0-9a-f]+$/i.test(short)) {
    return String(parseInt(short, 16));
  }

  return digitsOnly(process.env.BUILD_NUMBER || process.env.GITHUB_RUN_NUMBER) || '0';
}

function resolveVersion() {
  if (process.env.APP_VERSION && process.env.APP_VERSION.trim()) {
    return process.env.APP_VERSION.trim();
  }

  const branch = resolveBranch();
  const commit = resolveCommit();
  return `${branch}-${commit}`;
}

const version = resolveVersion();
const contents = `/* Auto-generated by scripts/generate-app-version.mjs — do not edit. */
export const APP_VERSION = '${version.replace(/'/g, "\\'")}';
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, contents, 'utf8');
console.log(`Wrote app version "${version}" → ${path.relative(frontendRoot, outFile)}`);
