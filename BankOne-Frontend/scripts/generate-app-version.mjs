#!/usr/bin/env node
/**
 * Writes src/environments/version.generated.ts from git (or CI env).
 * Prefer: git describe --tags --always
 * Fallback: short COMMIT_REF / CI SHA / "dev"
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.join(__dirname, '..');
const outFile = path.join(frontendRoot, 'src', 'environments', 'version.generated.ts');

function tryGit(cwd) {
  try {
    return execSync('git describe --tags --always --dirty', {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore']
    }).trim();
  } catch {
    try {
      return execSync('git rev-parse --short HEAD', {
        cwd,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore']
      }).trim();
    } catch {
      return null;
    }
  }
}

function resolveVersion() {
  if (process.env.APP_VERSION && process.env.APP_VERSION.trim()) {
    return process.env.APP_VERSION.trim();
  }

  const fromGit =
    tryGit(frontendRoot) ||
    tryGit(path.join(frontendRoot, '..')) ||
    tryGit(process.cwd());

  if (fromGit) {
    return fromGit;
  }

  const ciSha =
    process.env.COMMIT_REF ||
    process.env.GITHUB_SHA ||
    process.env.RENDER_GIT_COMMIT ||
    process.env.CF_PAGES_COMMIT_SHA ||
    '';

  if (ciSha.trim()) {
    return ciSha.trim().slice(0, 7);
  }

  return 'dev';
}

const version = resolveVersion();
const contents = `/* Auto-generated by scripts/generate-app-version.mjs — do not edit. */
export const APP_VERSION = '${version.replace(/'/g, "\\'")}';
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, contents, 'utf8');
console.log(`Wrote app version "${version}" → ${path.relative(frontendRoot, outFile)}`);
